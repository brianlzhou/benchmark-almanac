const FEED = "https://www.ai-wellbeing.org/";
const board: Leaderboard = {
  "benchmark": "ai-wellbeing-index-positive-experiences",
  "url": "https://www.ai-wellbeing.org/",
  "feed": "https://www.ai-wellbeing.org/",
  "terms": "The authors publish this public results feed; no separate score-reuse license is stated, and attribution remains with the authors."
,
  async fetch(): Promise<LeaderboardRow[]> {
    const source = await fetchText(FEED);
    const section = source.match(/<section id="wellbeing-index"[\s\S]*?<\/section>/)?.[0];
    if (!section) throw new Error('Wellbeing index section missing');
    const rows = [...section.matchAll(/title="([^"<>]+): ([\d.]+)%"/g)].map(m => ({model: text(m[1]), score: Number(m[2])}));
    if (!rows.length) throw new Error('Wellbeing index bars missing');
    return rows;
  },
};
export default board;
